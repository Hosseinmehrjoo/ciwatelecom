import fs from 'node:fs'
import path from 'node:path'
import { ensureDir, resolvePath } from '../store/fsutil.js'
import { loadPbx } from '../store/pbxStore.js'

const OUT_DIR = resolvePath('config/asterisk')

function header(title) {
  return `; Generated by CIWA Telecom — do not edit core/asterisk\n; ${title}\n; Generated-at: ${new Date().toISOString()}\n\n`
}

export function generateAsteriskConfigs(pbx = loadPbx()) {
  ensureDir(OUT_DIR)

  const files = {
    'manager.conf': buildManager(pbx),
    'rtp.conf': buildRtp(pbx),
    'pjsip.conf': buildPjsip(pbx),
    'extensions.conf': buildExtensions(pbx),
    'queues.conf': buildQueues(pbx),
    'voicemail.conf': buildVoicemail(pbx),
    'confbridge.conf': buildConfbridge(pbx),
    'musiconhold.conf': buildMoh(pbx),
    'ciwa_modules.conf': buildModules(),
  }

  for (const [name, content] of Object.entries(files)) {
    const target = path.join(OUT_DIR, name)
    fs.writeFileSync(target, content, 'utf8')
  }

  return {
    dir: 'config/asterisk',
    files: Object.keys(files),
    generatedAt: new Date().toISOString(),
  }
}

function buildManager(pbx) {
  return `${header('AMI')}
[general]
enabled = ${pbx.ami.enabled ? 'yes' : 'no'}
bindaddr = ${pbx.ami.bindIp}
port = ${pbx.ami.port}
webenabled = no
timestampevents = yes

[${pbx.ami.username}]
secret = ${pbx.ami.secret}
deny = 0.0.0.0/0.0.0.0
permit = 127.0.0.1/255.255.255.255
read = system,call,log,verbose,command,agent,user,config,dtmf,reporting,cdr,dialplan,originate
write = system,call,log,verbose,command,agent,user,config,dtmf,reporting,cdr,dialplan,originate
`
}

function buildRtp(pbx) {
  return `${header('RTP')}
[general]
rtpstart = ${pbx.sip.rtpStart}
rtpend = ${pbx.sip.rtpEnd}
`
}

function buildPjsip(pbx) {
  const lines = [header('PJSIP')]
  lines.push(`[transport-udp]
type = transport
protocol = udp
bind = ${pbx.sip.bindIp}:${pbx.sip.sipPort}
`)
  if (pbx.sip.tcpEnabled) {
    lines.push(`[transport-tcp]
type = transport
protocol = tcp
bind = ${pbx.sip.bindIp}:${pbx.sip.sipPort}
`)
  }
  if (pbx.sip.wssEnabled !== false) {
    lines.push(`[transport-wss]
type = transport
protocol = wss
bind = ${pbx.sip.bindIp}:${pbx.sip.wssPort || 8089}
`)
  }

  for (const ext of pbx.extensions) {
    const id = ext.number
    const webrtc = ext.webrtc !== false
    lines.push(`[${id}]
type = endpoint
context = from-internal
disallow = all
allow = ulaw,alaw,g722,opus
auth = ${id}
aors = ${id}
callerid = ${ext.name || id} <${id}>
${pbx.sip.externalIp ? `external_media_address = ${pbx.sip.externalIp}\nexternal_signaling_address = ${pbx.sip.externalIp}` : ''}
direct_media = no
rtp_symmetric = yes
force_rport = yes
rewrite_contact = yes
${webrtc ? `webrtc = yes
dtls_auto_generate_cert = yes
media_encryption = dtls
` : ''}
transport = transport-udp${pbx.sip.wssEnabled !== false ? ',transport-wss' : ''}

[${id}]
type = auth
auth_type = userpass
username = ${id}
password = ${ext.secret || id}

[${id}]
type = aor
max_contacts = ${ext.maxContacts || 3}
remove_existing = yes
`)
  }

  for (const trunk of pbx.trunks) {
    const id = trunk.id
    const hasAuth = Boolean(trunk.username && trunk.secret)
    lines.push(`[${id}]
type = endpoint
context = from-trunk
disallow = all
allow = ulaw,alaw,g722
${hasAuth ? `outbound_auth = ${id}` : ''}
aors = ${id}
from_domain = ${trunk.host || ''}
${trunk.outboundCallerId ? `callerid = ${trunk.outboundCallerId}` : ''}

`)
    if (hasAuth) {
      lines.push(`[${id}]
type = auth
auth_type = userpass
username = ${trunk.username || id}
password = ${trunk.secret || ''}

`)
    }
    lines.push(`[${id}]
type = aor
contact = sip:${trunk.host}:${trunk.port || 5060}

[${id}]
type = identify
endpoint = ${id}
match = ${trunk.host || '0.0.0.0'}

`)
    if (trunk.register) {
      lines.push(`[${id}]
type = registration
outbound_auth = ${id}
server_uri = sip:${trunk.host}
client_uri = sip:${trunk.username || id}@${trunk.host}
retry_interval = 60

`)
    }
  }

  return lines.join('\n')
}

function recordingSubroutine() {
  return `
[sub-ciwa-record]
exten => s,1,NoOp(CIWA recording \${ARG1})
 same => n,Set(MONITOR_FILENAME=/var/spool/asterisk/monitor/\${ARG1}-\${STRFTIME(\${EPOCH},,%Y%m%d-%H%M%S)}-\${UNIQUEID}.wav)
 same => n,MixMonitor(\${MONITOR_FILENAME},b)
 same => n,Return()
`
}

function buildExtensions(pbx) {
  const lines = [header('Dialplan'), '[general]\nstatic = yes\nwriteprotect = no\n', recordingSubroutine(), '\n[from-internal]']

  const recorders = new Set(
    (pbx.extensions || []).filter((ext) => ext.recordCalls).map((ext) => String(ext.number)),
  )
  const recordMacro = (label) => (recorders.size ? ` same => n,Gosub(sub-ciwa-record,s,1(${label}))\n` : '')

  for (const ext of pbx.extensions) {
    lines.push(`exten => ${ext.number},1,NoOp(CIWA extension ${ext.number})`)
    lines.push(recordMacro(`ext-${ext.number}`))
    lines.push(` same => n,Dial(PJSIP/${ext.number},${ext.ringTimeout || 30})`)
    if (ext.voicemail) lines.push(` same => n,VoiceMail(${ext.number}@default,u)`)
    lines.push(` same => n,Hangup()`)
  }

  for (const group of pbx.ringGroups) {
    const members = (group.members || []).map((m) => `PJSIP/${m}`).join('&')
    const dialOpts = group.strategy === 'hunt' ? 'h' : 'r'
    lines.push(`exten => ${group.number},1,NoOp(CIWA ring group ${group.name || group.number})`)
    lines.push(recordMacro(`rg-${group.number}`))
    lines.push(` same => n,Dial(${members},${group.timeout || 25},${dialOpts})`)
    lines.push(` same => n,Hangup()`)
  }

  for (const queue of pbx.queues) {
    lines.push(`exten => ${queue.number},1,NoOp(CIWA queue ${queue.name || queue.number})`)
    lines.push(` same => n,Queue(${queue.id},${queue.options || 'tT'})`)
    lines.push(` same => n,Hangup()`)
  }

  for (const conf of pbx.conferences) {
    lines.push(`exten => ${conf.number},1,NoOp(CIWA conference ${conf.name || conf.number})`)
    lines.push(` same => n,ConfBridge(${conf.id})`)
    lines.push(` same => n,Hangup()`)
  }

  for (const route of pbx.outboundRoutes) {
    const pattern = route.pattern || '_X.'
    const trunk = route.trunkId
    lines.push(`exten => ${pattern},1,NoOp(CIWA outbound ${route.name || pattern})`)
    lines.push(recordMacro('out-${CALLERID(num)}'))
    lines.push(` same => n,Set(CALLERID(num)=${route.callerId || '${CALLERID(num)}'})`)
    lines.push(` same => n,Dial(PJSIP/\${EXTEN}@${trunk},${route.timeout || 60})`)
    lines.push(` same => n,Hangup()`)
  }

  for (const tc of pbx.timeConditions || []) {
    const range = tc.timeRange || '09:00-17:00'
    const weekdays = tc.weekdays || 'mon-fri'
    lines.push(`\n[tc-${tc.id}]`)
    lines.push(`exten => s,1,NoOp(CIWA time condition ${tc.name || tc.id})`)
    lines.push(` same => n,GotoIfTime(${range},${weekdays},*,*?match,1)`)
    lines.push(` same => n,Goto(miss,1)`)
    lines.push(`exten => match,1,Goto(from-internal,${tc.matchDestination},1)`)
    lines.push(`exten => miss,1,Goto(from-internal,${tc.missDestination},1)`)
  }

  lines.push('\n[from-trunk]')
  for (const route of pbx.inboundRoutes) {
    const did = route.did || 's'
    lines.push(`exten => ${did},1,NoOp(CIWA inbound ${route.name || did})`)
    lines.push(recordMacro(`in-${did}`))
    if (route.destinationType === 'extension') {
      lines.push(` same => n,Goto(from-internal,${route.destination},1)`)
    } else if (route.destinationType === 'queue') {
      lines.push(` same => n,Queue(${route.destination})`)
    } else if (route.destinationType === 'ivr') {
      lines.push(` same => n,Goto(ivr-${route.destination},s,1)`)
    } else if (route.destinationType === 'time-condition' || route.destinationType === 'timeCondition') {
      lines.push(` same => n,Goto(tc-${route.destination},s,1)`)
    } else if (route.destinationType === 'hangup') {
      lines.push(` same => n,Hangup()`)
    } else {
      lines.push(` same => n,Hangup()`)
    }
  }

  for (const ivr of pbx.ivrs) {
    const invalid = ivr.invalidDestination || 's'
    const timeoutDest = ivr.timeoutDestination || invalid
    lines.push(`\n[ivr-${ivr.id}]`)
    lines.push('exten => s,1,Answer()')
    lines.push(` same => n,Background(${ivr.greeting || 'demo-congrats'})`)
    lines.push(' same => n,WaitExten(8)')
    lines.push(`exten => i,1,Goto(from-internal,${invalid},1)`)
    lines.push(`exten => t,1,Goto(from-internal,${timeoutDest},1)`)
    for (const option of ivr.options || []) {
      if (option.destinationType === 'queue') {
        lines.push(`exten => ${option.digit},1,Queue(${option.destination})`)
      } else if (option.destinationType === 'ivr') {
        lines.push(`exten => ${option.digit},1,Goto(ivr-${option.destination},s,1)`)
      } else {
        lines.push(`exten => ${option.digit},1,Goto(from-internal,${option.destination},1)`)
      }
    }
  }

  return `${lines.join('\n')}\n`
}

function buildQueues(pbx) {
  const lines = [header('Queues')]
  for (const queue of pbx.queues) {
    lines.push(`[${queue.id}]
strategy = ${queue.strategy || 'ringall'}
timeout = ${queue.timeout || 20}
retry = ${queue.retry || 5}
wrapuptime = ${queue.wrapup || 10}
maxlen = ${queue.maxlen || 0}
musicclass = ${queue.moh || 'default'}
`)
    for (const member of queue.members || []) {
      lines.push(`member => PJSIP/${member}`)
    }
    lines.push('')
  }
  return lines.join('\n')
}

function buildVoicemail(pbx) {
  const lines = [header('Voicemail'), '[general]\nformat = wav49|gsm|wav\n\n[default]']
  for (const box of pbx.voicemailBoxes) {
    lines.push(`${box.number} => ${box.pin || '0000'},${box.name || box.number},${box.email || ''}`)
  }
  for (const ext of pbx.extensions.filter((e) => e.voicemail)) {
    if (!pbx.voicemailBoxes.some((b) => b.number === ext.number)) {
      lines.push(`${ext.number} => ${ext.vmPin || '0000'},${ext.name || ext.number},`)
    }
  }
  return `${lines.join('\n')}\n`
}

function buildConfbridge(pbx) {
  const lines = [header('ConfBridge'), '[general]\n']
  for (const conf of pbx.conferences) {
    lines.push(`[${conf.id}]
type = bridge
max_members = ${conf.maxMembers || 20}
`)
  }
  return lines.join('\n')
}

function buildMoh(pbx) {
  const lines = [header('Music on Hold'), '[general]\n\n[default]\nmode = files\ndirectory = moh\n']
  for (const moh of pbx.mohClasses) {
    lines.push(`[${moh.id}]
mode = files
directory = ${moh.directory || `moh/${moh.id}`}
`)
  }
  return lines.join('\n')
}

function buildModules() {
  return `${header('Module hints')}
; Point Asterisk --sysconfdir to config/asterisk (outside core/asterisk).
; Example runtime:
;   asterisk -C ${OUT_DIR}/asterisk.conf
`
}
