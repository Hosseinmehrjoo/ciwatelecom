import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { confDial, confIdent, confPath, confText } from './confSafe.js'
import { writeCiscoProvisioning } from './ciscoProv.js'
import { ensureDir, resolvePath } from '../store/fsutil.js'
import { loadPbx } from '../store/pbxStore.js'

const OUT_DIR = resolvePath('config/asterisk')

function header(title) {
  return `; Generated by CIWA Telecom — do not edit core/asterisk\n; ${title}\n; Generated-at: ${new Date().toISOString()}\n\n`
}

export function generateAsteriskConfigs(pbx = loadPbx(), outDir = OUT_DIR, options = {}) {
  ensureDir(outDir)

  const files = {
    'manager.conf': buildManager(pbx),
    'rtp.conf': buildRtp(pbx),
    'pjsip.conf': buildPjsip(pbx),
    'extensions.conf': buildExtensions(pbx),
    'queues.conf': buildQueues(pbx),
    'voicemail.conf': buildVoicemail(pbx),
    'confbridge.conf': buildConfbridge(pbx),
    'musiconhold.conf': buildMoh(pbx),
    'ciwa_modules.conf': buildModules(),
  }

  for (const [name, content] of Object.entries(files)) {
    const target = path.join(outDir, name)
    fs.writeFileSync(target, content, 'utf8')
  }

  const tftpDir = options.tftpDir ?? (outDir === OUT_DIR ? resolvePath('tftp') : null)
  const cisco = tftpDir ? writeCiscoProvisioning(pbx, tftpDir) : null

  return {
    dir: 'config/asterisk',
    files: Object.keys(files),
    cisco,
    generatedAt: new Date().toISOString(),
  }
}

export function dockerAmiPermits() {
  if (!fs.existsSync('/.dockerenv')) return []
  const permits = []
  for (const entries of Object.values(os.networkInterfaces())) {
    for (const entry of entries || []) {
      if (entry.internal || entry.family !== 'IPv4' || !entry.cidr) continue
      const [address, prefixText] = entry.cidr.split('/')
      const prefix = Number(prefixText)
      if (!address || !Number.isInteger(prefix) || prefix < 8 || prefix > 32) continue
      permits.push(ipv4Permit(address, prefix))
    }
  }
  return [...new Set(permits)]
}

function ipv4Permit(address, prefix) {
  const parts = address.split('.').map((part) => Number(part))
  if (parts.length !== 4 || parts.some((part) => part < 0 || part > 255 || Number.isNaN(part))) return ''
  const mask = prefix === 0 ? 0 : ((0xffffffff << (32 - prefix)) >>> 0)
  const ip = (((parts[0] << 24) >>> 0) + (parts[1] << 16) + (parts[2] << 8) + parts[3]) >>> 0
  const network = (ip & mask) >>> 0
  const net = [24, 16, 8, 0].map((shift) => (network >>> shift) & 255).join('.')
  const maskText = [24, 16, 8, 0].map((shift) => (mask >>> shift) & 255).join('.')
  return `${net}/${maskText}`
}

function buildManager(pbx) {
  const extraPermits = dockerAmiPermits().filter(Boolean)
  const bind = extraPermits.length ? '0.0.0.0' : confIdent(pbx.ami.bindIp) || '127.0.0.1'
  const permits = ['127.0.0.1/255.255.255.255', ...extraPermits]
  const user = confIdent(pbx.ami.username) || 'ciwa'
  const secret = confText(pbx.ami.secret).replace(/[^\x20-\x7E]/g, '')
  return `${header('AMI')}
[general]
enabled = ${pbx.ami.enabled ? 'yes' : 'no'}
bindaddr = ${bind}
port = ${Number(pbx.ami.port) || 5038}
webenabled = no
timestampevents = yes

[${user}]
secret = ${secret}
deny = 0.0.0.0/0.0.0.0
${permits.map((permit) => `permit = ${permit}`).join('\n')}
read = system,call,log,verbose,command,agent,user,config,dtmf,reporting,cdr,dialplan,originate
write = system,call,log,verbose,command,agent,user,config,dtmf,reporting,cdr,dialplan,originate
`
}

function buildRtp(pbx) {
  return `${header('RTP')}
[general]
rtpstart = ${pbx.sip.rtpStart}
rtpend = ${pbx.sip.rtpEnd}
`
}

function buildPjsip(pbx) {
  const lines = [header('PJSIP')]
  lines.push(`[transport-udp]
type = transport
protocol = udp
bind = ${confIdent(pbx.sip.bindIp) || '0.0.0.0'}:${Number(pbx.sip.sipPort) || 5060}
`)
  if (pbx.sip.tcpEnabled) {
    lines.push(`[transport-tcp]
type = transport
protocol = tcp
bind = ${confIdent(pbx.sip.bindIp) || '0.0.0.0'}:${Number(pbx.sip.sipPort) || 5060}
`)
  }
  if (pbx.sip.wssEnabled !== false) {
    lines.push(`[transport-wss]
type = transport
protocol = wss
bind = ${confIdent(pbx.sip.bindIp) || '0.0.0.0'}:${Number(pbx.sip.wssPort) || 8089}
`)
  }

  for (const ext of pbx.extensions) {
    const id = confIdent(ext.number)
    if (!id) continue
    const phoneType = ext.phoneType || (ext.webrtc === false ? 'sip' : 'webrtc')
    const webrtc = phoneType === 'webrtc'
    const cisco = String(phoneType).startsWith('cisco')
    const desk = cisco || phoneType === 'sip'
    lines.push(`[${id}]
type = endpoint
context = from-internal
disallow = all
allow = ${desk ? 'ulaw,alaw' : 'ulaw,alaw,g722,opus'}
auth = ${id}
aors = ${id}
callerid = ${confText(ext.name || id)} <${id}>
${pbx.sip.externalIp ? `external_media_address = ${confIdent(pbx.sip.externalIp)}\nexternal_signaling_address = ${confIdent(pbx.sip.externalIp)}` : ''}
direct_media = no
rtp_symmetric = yes
force_rport = yes
rewrite_contact = yes
${desk ? `dtmf_mode = rfc4733
media_use_received_transport = yes
` : ''}${webrtc ? `webrtc = yes
dtls_auto_generate_cert = yes
media_encryption = dtls
` : ''}
transport = ${desk ? 'transport-udp' : `transport-udp${pbx.sip.wssEnabled !== false ? ',transport-wss' : ''}`}

[${id}]
type = auth
auth_type = userpass
username = ${id}
password = ${confText(ext.secret || id)}

[${id}]
type = aor
max_contacts = ${ext.maxContacts || 3}
remove_existing = yes
`)
  }

  for (const trunk of pbx.trunks) {
    const id = confIdent(trunk.id)
    if (!id) continue
    const host = confIdent(trunk.host)
    const hasAuth = Boolean(trunk.username && trunk.secret)
    lines.push(`[${id}]
type = endpoint
context = from-trunk
disallow = all
allow = ulaw,alaw,g722
${hasAuth ? `outbound_auth = ${id}` : ''}
aors = ${id}
from_domain = ${host}
${trunk.outboundCallerId ? `callerid = ${confText(trunk.outboundCallerId)}` : ''}

`)
    if (hasAuth) {
      lines.push(`[${id}]
type = auth
auth_type = userpass
username = ${confIdent(trunk.username) || id}
password = ${confText(trunk.secret || '')}

`)
    }
    lines.push(`[${id}]
type = aor
contact = sip:${host}:${Number(trunk.port) || 5060}

[${id}]
type = identify
endpoint = ${id}
match = ${host || '0.0.0.0'}

`)
    if (trunk.register) {
      lines.push(`[${id}]
type = registration
outbound_auth = ${id}
server_uri = sip:${host}
client_uri = sip:${confIdent(trunk.username) || id}@${host}
retry_interval = 60

`)
    }
  }

  return lines.join('\n')
}

function recordingSubroutine() {
  return `
[sub-ciwa-record]
exten => s,1,NoOp(CIWA recording \${ARG1})
 same => n,Set(MONITOR_FILENAME=/var/spool/asterisk/monitor/\${ARG1}-\${STRFTIME(\${EPOCH},,%Y%m%d-%H%M%S)}-\${UNIQUEID}.wav)
 same => n,MixMonitor(\${MONITOR_FILENAME},b)
 same => n,Return()
`
}

function buildExtensions(pbx) {
  const lines = [header('Dialplan'), '[general]\nstatic = yes\nwriteprotect = no\n', recordingSubroutine(), '\n[from-internal]']

  const recorders = new Set(
    (pbx.extensions || []).filter((ext) => ext.recordCalls).map((ext) => String(ext.number)),
  )
  const recordMacro = (label) => (recorders.size ? ` same => n,Gosub(sub-ciwa-record,s,1(${label}))\n` : '')

  for (const ext of pbx.extensions) {
    const number = confIdent(ext.number)
    if (!number) continue
    lines.push(`exten => ${number},1,NoOp(CIWA extension ${number})`)
    lines.push(recordMacro(`ext-${number}`))
    lines.push(` same => n,Dial(PJSIP/${number},${Number(ext.ringTimeout) || 30})`)
    if (ext.voicemail) lines.push(` same => n,VoiceMail(${number}@default,u)`)
    lines.push(` same => n,Hangup()`)
  }

  for (const group of pbx.ringGroups) {
    const number = confIdent(group.number)
    if (!number) continue
    const members = (group.members || []).map((m) => `PJSIP/${confIdent(m)}`).filter((m) => m !== 'PJSIP/').join('&')
    const dialOpts = group.strategy === 'hunt' ? 'h' : 'r'
    lines.push(`exten => ${number},1,NoOp(CIWA ring group ${confText(group.name || number)})`)
    lines.push(recordMacro(`rg-${number}`))
    lines.push(` same => n,Dial(${members},${Number(group.timeout) || 25},${dialOpts})`)
    lines.push(` same => n,Hangup()`)
  }

  for (const queue of pbx.queues) {
    const number = confIdent(queue.number)
    const id = confIdent(queue.id)
    if (!number || !id) continue
    const options = String(queue.options || 'tT').replace(/[^A-Za-z]/g, '') || 'tT'
    lines.push(`exten => ${number},1,NoOp(CIWA queue ${confText(queue.name || number)})`)
    lines.push(` same => n,Queue(${id},${options})`)
    lines.push(` same => n,Hangup()`)
  }

  for (const conf of pbx.conferences) {
    const number = confIdent(conf.number)
    const id = confIdent(conf.id)
    if (!number || !id) continue
    lines.push(`exten => ${number},1,NoOp(CIWA conference ${confText(conf.name || number)})`)
    lines.push(` same => n,ConfBridge(${id})`)
    lines.push(` same => n,Hangup()`)
  }

  for (const route of pbx.outboundRoutes) {
    const pattern = confDial(route.pattern || '_X.') || '_X.'
    const trunk = confIdent(route.trunkId)
    if (!trunk) continue
    const caller = route.callerId ? confDial(route.callerId) : '${CALLERID(num)}'
    lines.push(`exten => ${pattern},1,NoOp(CIWA outbound ${confText(route.name || pattern)})`)
    lines.push(recordMacro('out-${CALLERID(num)}'))
    lines.push(` same => n,Set(CALLERID(num)=${caller})`)
    lines.push(` same => n,Dial(PJSIP/\${EXTEN}@${trunk},${Number(route.timeout) || 60})`)
    lines.push(` same => n,Hangup()`)
  }

  for (const tc of pbx.timeConditions || []) {
    const id = confIdent(tc.id)
    if (!id) continue
    const range = /^\d{2}:\d{2}-\d{2}:\d{2}$/.test(String(tc.timeRange || '')) ? tc.timeRange : '09:00-17:00'
    const weekdays = /^[a-z0-9,-]+$/i.test(String(tc.weekdays || '')) ? tc.weekdays : 'mon-fri'
    lines.push(`\n[tc-${id}]`)
    lines.push(`exten => s,1,NoOp(CIWA time condition ${confText(tc.name || id)})`)
    lines.push(` same => n,GotoIfTime(${range},${weekdays},*,*?match,1)`)
    lines.push(` same => n,Goto(miss,1)`)
    lines.push(`exten => match,1,Goto(from-internal,${confIdent(tc.matchDestination)},1)`)
    lines.push(`exten => miss,1,Goto(from-internal,${confIdent(tc.missDestination)},1)`)
  }

  lines.push('\n[from-trunk]')
  for (const route of pbx.inboundRoutes) {
    const did = confDial(route.did || 's') || 's'
    const dest = confIdent(route.destination)
    lines.push(`exten => ${did},1,NoOp(CIWA inbound ${confText(route.name || did)})`)
    lines.push(recordMacro(`in-${did}`))
    if (route.destinationType === 'extension') {
      lines.push(` same => n,Goto(from-internal,${dest},1)`)
    } else if (route.destinationType === 'queue') {
      lines.push(` same => n,Queue(${dest})`)
    } else if (route.destinationType === 'ivr') {
      lines.push(` same => n,Goto(ivr-${dest},s,1)`)
    } else if (route.destinationType === 'time-condition' || route.destinationType === 'timeCondition') {
      lines.push(` same => n,Goto(tc-${dest},s,1)`)
    } else {
      lines.push(` same => n,Hangup()`)
    }
  }

  for (const ivr of pbx.ivrs) {
    const id = confIdent(ivr.id)
    if (!id) continue
    const invalid = confIdent(ivr.invalidDestination) || 's'
    const timeoutDest = confIdent(ivr.timeoutDestination) || invalid
    const greeting = confPath(ivr.greeting) || 'demo-congrats'
    lines.push(`\n[ivr-${id}]`)
    lines.push('exten => s,1,Answer()')
    lines.push(` same => n,Background(${greeting})`)
    lines.push(' same => n,WaitExten(8)')
    lines.push(`exten => i,1,Goto(from-internal,${invalid},1)`)
    lines.push(`exten => t,1,Goto(from-internal,${timeoutDest},1)`)
    for (const option of ivr.options || []) {
      const digit = confDial(option.digit)
      const destination = confIdent(option.destination)
      if (!digit || !destination) continue
      if (option.destinationType === 'queue') {
        lines.push(`exten => ${digit},1,Queue(${destination})`)
      } else if (option.destinationType === 'ivr') {
        lines.push(`exten => ${digit},1,Goto(ivr-${destination},s,1)`)
      } else {
        lines.push(`exten => ${digit},1,Goto(from-internal,${destination},1)`)
      }
    }
  }

  return `${lines.join('\n')}\n`
}

function buildQueues(pbx) {
  const lines = [header('Queues')]
  for (const queue of pbx.queues) {
    const id = confIdent(queue.id)
    if (!id) continue
    const strategy = ['ringall', 'leastrecent', 'fewestcalls', 'random', 'rrmemory', 'linear', 'wrandom'].includes(queue.strategy) ? queue.strategy : 'ringall'
    lines.push(`[${id}]
strategy = ${strategy}
timeout = ${queue.timeout || 20}
retry = ${queue.retry || 5}
wrapuptime = ${queue.wrapup || 10}
maxlen = ${queue.maxlen || 0}
musicclass = ${confIdent(queue.moh) || 'default'}
`)
    for (const member of queue.members || []) {
      const iface = confIdent(member)
      if (iface) lines.push(`member => PJSIP/${iface}`)
    }
    lines.push('')
  }
  return lines.join('\n')
}

function buildVoicemail(pbx) {
  const lines = [header('Voicemail'), '[general]\nformat = wav49|gsm|wav\n\n[default]']
  for (const box of pbx.voicemailBoxes) {
    const number = confIdent(box.number)
    if (!number) continue
    const pin = String(box.pin || '0000').replace(/\D/g, '').slice(0, 12) || '0000'
    lines.push(`${number} => ${pin},${confText(box.name || number)},${confText(box.email || '').replace(/[^\w.@+-]/g, '')}`)
  }
  for (const ext of pbx.extensions.filter((e) => e.voicemail)) {
    const number = confIdent(ext.number)
    if (!number || pbx.voicemailBoxes.some((b) => confIdent(b.number) === number)) continue
    const pin = String(ext.vmPin || '0000').replace(/\D/g, '').slice(0, 12) || '0000'
    lines.push(`${number} => ${pin},${confText(ext.name || number)},`)
  }
  return `${lines.join('\n')}\n`
}

function buildConfbridge(pbx) {
  const lines = [header('ConfBridge'), '[general]\n']
  for (const conf of pbx.conferences) {
    const id = confIdent(conf.id)
    if (!id) continue
    lines.push(`[${id}]
type = bridge
max_members = ${Number(conf.maxMembers) || 20}
`)
  }
  return lines.join('\n')
}

function buildMoh(pbx) {
  const lines = [header('Music on Hold'), '[general]\n\n[default]\nmode = files\ndirectory = moh\n']
  for (const moh of pbx.mohClasses) {
    const id = confIdent(moh.id)
    if (!id) continue
    const directory = confPath(moh.directory) || `moh/${id}`
    if (directory.includes('..')) continue
    lines.push(`[${id}]
mode = files
directory = ${directory}
`)
  }
  return lines.join('\n')
}

function buildModules() {
  return `${header('Module hints')}
; Point Asterisk --sysconfdir to config/asterisk (outside core/asterisk).
; Example runtime:
;   asterisk -C ${OUT_DIR}/asterisk.conf
`
}
