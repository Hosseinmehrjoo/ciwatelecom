import { execFile } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { promisify } from 'node:util'
import { loadSystem, saveSystem } from '../store/systemStore.js'
import { ensureDir, resolvePath } from '../store/fsutil.js'

const execFileAsync = promisify(execFile)

async function run(cmd, args = []) {
  try {
    const { stdout, stderr } = await execFileAsync(cmd, args, { timeout: 8000, maxBuffer: 2_000_000 })
    return { ok: true, stdout: stdout.trim(), stderr: stderr.trim() }
  } catch (error) {
    return {
      ok: false,
      stdout: error.stdout?.toString?.().trim?.() || '',
      stderr: error.stderr?.toString?.().trim?.() || (error instanceof Error ? error.message : 'command failed'),
    }
  }
}

export async function getNetworkStatus() {
  const desired = loadSystem()
  const addr = await run('ip', ['-j', 'addr'])
  const route = await run('ip', ['-j', 'route'])
  const hostname = await run('hostname')
  let interfaces = []
  let routes = []
  if (addr.ok) {
    try {
      interfaces = JSON.parse(addr.stdout).map((iface) => ({
        name: iface.ifname,
        state: iface.operstate,
        mac: iface.address,
        mtu: iface.mtu,
        addresses: (iface.addr_info || []).map((info) => ({
          family: info.family,
          address: info.local,
          prefix: info.prefixlen,
          scope: info.scope,
        })),
      }))
    } catch {
      interfaces = []
    }
  }
  if (route.ok) {
    try {
      routes = JSON.parse(route.stdout)
    } catch {
      routes = []
    }
  }

  let dns = []
  try {
    const resolv = fs.readFileSync('/etc/resolv.conf', 'utf8')
    dns = resolv.split('\n').filter((line) => line.startsWith('nameserver')).map((line) => line.split(/\s+/)[1]).filter(Boolean)
  } catch {
    dns = desired.dns || []
  }

  return {
    live: {
      hostname: hostname.ok ? hostname.stdout : desired.hostname,
      interfaces,
      routes,
      dns,
      readable: addr.ok,
      error: addr.ok ? null : addr.stderr,
    },
    desired: {
      hostname: desired.hostname,
      dns: desired.dns,
      gateway: desired.gateway,
      interfaces: desired.interfaces,
    },
  }
}

export async function saveNetworkDesired(payload) {
  const system = loadSystem()
  system.hostname = payload.hostname === undefined ? system.hostname : assertHostname(payload.hostname)
  system.dns = payload.dns === undefined ? system.dns : (Array.isArray(payload.dns) ? payload.dns : String(payload.dns).split(',')).map((item) => assertIpv4(String(item).trim(), 'DNS')).filter(Boolean)
  system.gateway = payload.gateway === undefined ? system.gateway : assertIpv4(payload.gateway, 'درگاه')
  system.interfaces = payload.interfaces === undefined ? system.interfaces : (payload.interfaces || []).map(assertInterface)
  await saveSystem(system)
  const planPath = resolvePath('config/ciwa/network.desired.json')
  fs.writeFileSync(planPath, `${JSON.stringify(system, null, 2)}\n`)
  return { ok: true, desired: system, planPath: 'config/ciwa/network.desired.json' }
}

export async function applyNetworkDesired() {
  const system = loadSystem()
  const scriptDir = resolvePath('scripts/maintenance')
  ensureDir(scriptDir)
  const scriptPath = path.join(scriptDir, 'apply-network.sh')
  const lines = ['#!/usr/bin/env bash', 'set -euo pipefail', '# Generated by CIWA Telecom UI', '']
  if (system.hostname) lines.push(`hostnamectl set-hostname '${shell(system.hostname)}' || hostname '${shell(system.hostname)}'`)
  if (system.gateway) lines.push(`ip route replace default via '${shell(system.gateway)}' || true`)
  for (const iface of system.interfaces || []) {
    if (!iface.name || !iface.address) continue
    lines.push(`ip addr replace '${shell(iface.address)}' dev '${shell(iface.name)}'`)
    if (iface.up !== false) lines.push(`ip link set '${shell(iface.name)}' up`)
  }
  fs.writeFileSync(scriptPath, `${lines.join('\n')}\n`, { mode: 0o755 })
  const result = await run('bash', [scriptPath])
  return {
    ok: result.ok,
    script: 'scripts/maintenance/apply-network.sh',
    stdout: result.stdout,
    stderr: result.stderr,
    note: result.ok ? 'اعمال شد' : 'برای اعمال شبکه معمولاً دسترسی root لازم است. اسکریپت ذخیره شد.',
  }
}

export async function getFirewallStatus() {
  const system = loadSystem()
  const nft = await run('nft', ['list', 'ruleset'])
  const iptables = nft.ok ? null : await run('iptables', ['-S'])
  return {
    desired: system.firewall,
    live: {
      backend: nft.ok ? 'nftables' : iptables?.ok ? 'iptables' : 'unavailable',
      readable: nft.ok || Boolean(iptables?.ok),
      ruleset: nft.ok ? nft.stdout : iptables?.stdout || '',
      error: nft.ok || iptables?.ok ? null : (nft.stderr || iptables?.stderr || 'permission denied'),
    },
  }
}

export async function saveFirewallDesired(firewall) {
  const system = loadSystem()
  const next = normalizeFirewall({ ...system.firewall, ...firewall, rules: firewall.rules || system.firewall.rules })
  system.firewall = next
  await saveSystem(system)
  writeNftFile(system.firewall)
  return { ok: true, firewall: system.firewall, file: 'config/ciwa/firewall.nft' }
}

export async function applyFirewallDesired() {
  const system = loadSystem()
  const file = writeNftFile(system.firewall)
  const result = await run('nft', ['-f', resolvePath(file)])
  return {
    ok: result.ok,
    file,
    stdout: result.stdout,
    stderr: result.stderr,
    note: result.ok ? 'فایروال اعمال شد' : 'اعمال فایروال نیاز به root دارد. فایل nft ذخیره شد.',
  }
}

function writeNftFile(firewall) {
  const file = resolvePath('config/ciwa/firewall.nft')
  ensureDir(resolvePath('config/ciwa'))
  const safe = normalizeFirewall(firewall)
  const lines = [
    '#!/usr/sbin/nft -f',
    '# Generated by CIWA Telecom UI — does not modify core/asterisk',
    'destroy table inet ciwa_filter',
    'table inet ciwa_filter {',
    '  chain input {',
    `    type filter hook input priority 0; policy ${safe.defaultIncoming};`,
    '    ct state established,related accept',
    '    iif lo accept',
  ]
  for (const rule of safe.rules || []) {
    if (rule.enabled === false) continue
    const action = rule.action
    const proto = rule.protocol !== 'any' ? rule.protocol : null
    const port = rule.port
    const source = rule.source !== 'any' ? `ip saddr ${rule.source}` : ''
    let expr = '    '
    if (source) expr += `${source} `
    if (proto) expr += `${proto} `
    if (port) expr += `dport ${port} `
    expr += `${action} comment "${rule.comment}"`
    lines.push(expr)
  }
  lines.push('  }')
  lines.push('  chain forward {')
  lines.push('    type filter hook forward priority 0; policy drop;')
  lines.push('  }')
  lines.push('  chain output {')
  lines.push(`    type filter hook output priority 0; policy ${safe.defaultOutgoing};`)
  lines.push('  }')
  lines.push('}')
  fs.writeFileSync(file, `${lines.join('\n')}\n`)
  return 'config/ciwa/firewall.nft'
}

function shell(value) {
  return String(value).replace(/'/g, `'"'"'`)
}

function bad(message) {
  const error = new Error(message)
  error.status = 400
  return error
}

function assertHostname(value) {
  const text = String(value ?? '').trim()
  if (!text) return ''
  if (!/^[A-Za-z0-9][A-Za-z0-9.-]{0,62}$/.test(text) || text.includes('..')) throw bad('نام میزبان نامعتبر است.')
  return text
}

function assertIpv4(value, label) {
  const text = String(value ?? '').trim()
  if (!text) return ''
  const [addr, prefix] = text.split('/')
  const parts = addr.split('.')
  if (parts.length !== 4 || parts.some((part) => !/^\d{1,3}$/.test(part) || Number(part) > 255)) {
    throw bad(`${label} باید IPv4 باشد.`)
  }
  if (prefix !== undefined && (!/^\d{1,2}$/.test(prefix) || Number(prefix) > 32)) throw bad(`${label} پیشوند نامعتبر دارد.`)
  return text
}

function assertInterface(iface) {
  const name = String(iface?.name || '').trim()
  if (!/^[A-Za-z0-9_.:-]{1,15}$/.test(name)) throw bad('نام اینترفیس نامعتبر است.')
  return {
    name,
    address: assertIpv4(iface.address, 'آدرس اینترفیس'),
    up: iface.up !== false,
  }
}

function normalizeFirewall(firewall = {}) {
  const policy = (value, fallback) => (value === 'accept' || value === 'drop' ? value : fallback)
  const rules = (firewall.rules || []).map((rule, index) => {
    const protocol = ['tcp', 'udp', 'any'].includes(rule.protocol) ? rule.protocol : 'any'
    const port = String(rule.port || '').trim()
    if (port && !/^\d{1,5}(-\d{1,5})?$/.test(port)) throw bad('پورت قانون فایروال نامعتبر است.')
    if (port && port.split('-').some((part) => Number(part) < 1 || Number(part) > 65535)) throw bad('پورت قانون فایروال نامعتبر است.')
    const source = !rule.source || rule.source === 'any' ? 'any' : assertIpv4(rule.source, 'مبدأ قانون')
    const comment = String(rule.comment || rule.id || `rule-${index + 1}`).replace(/[^\w .\-]/g, '').slice(0, 80) || `rule-${index + 1}`
    return {
      ...rule,
      protocol,
      port,
      source,
      action: rule.action === 'drop' ? 'drop' : 'accept',
      comment,
    }
  })
  return {
    ...firewall,
    defaultIncoming: policy(firewall.defaultIncoming, 'drop'),
    defaultOutgoing: policy(firewall.defaultOutgoing, 'accept'),
    rules,
  }
}
